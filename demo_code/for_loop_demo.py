def main():
    # Print integers from 0 and 10
    for number in range(11):
        print(number)

# Print integers from 5 and 10
    print("\n\n")
    for number in range(5, 11):
        print(number)

# Print even integers from 0 and 10
    print("\n\n")
    for number in range(0, 11, 2):
        print(number)


main()